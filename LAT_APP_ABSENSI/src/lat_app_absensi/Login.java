    private void buttonLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonLoginActionPerformed
        // TODO add your handling code here:
        if (!jUsername.getText().isEmpty() && !jPassword.getText().isEmpty()) {
            try {
                String sql = "SELECT * FROM tabel_pengguna "
                        + "WHERE username = '" + jUsername.getText() + "' and password = '" + jPassword.getText() + "'";
                rs = con.createStatement().executeQuery(sql);
                if (rs.next()) {
                    jPengguna.setText("Hi, " + rs.getString("username") + "!");
                    this.dispose();
                    new Dashboard().setVisible(true);
                } else {
                    JOptionPane.showMessageDialog(null, "Username atau password salah");
                }
            } catch (Exception e) {
                System.out.println(e);
            }

        } else {
            JOptionPane.showMessageDialog(null, "Username atau Password wajib diisi");
        }
    }//GEN-LAST:event_buttonLoginActionPerformed

