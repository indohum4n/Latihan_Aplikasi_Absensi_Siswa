    private void buttonHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonHapusActionPerformed
        // TODO add your handling code here:
        try {
            int confirm = JOptionPane.showConfirmDialog(this,
                    "Apakah Anda yakin ingin menghapus data dengan username " + jUsername.getText() + "?",
                    "Konfirmasi", JOptionPane.YES_NO_OPTION);
            if (confirm == JOptionPane.YES_OPTION) {
                String sql = "DELETE from tabel_pengguna WHERE idpengguna = " + jID.getText() + "";
                con.createStatement().executeUpdate(sql);
                JOptionPane.showMessageDialog(null, "Berhasil Dihapus!");
                awal();
            } else if (confirm == JOptionPane.NO_OPTION) {
                //
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Gagal Dihapus!");
        }
    }//GEN-LAST:event_buttonHapusActionPerformed

    private void buttonUbahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonUbahActionPerformed
        // TODO add your handling code here:
        if (!jUsername.getText().isEmpty() && !jPassword.getText().isEmpty() && !jRePassword.getText().isEmpty()) {
            // kurang yang password dan repassword
            if (jRePassword.getText().equals(jPassword.getText())) {
                try {
                    String sql = "UPDATE tabel_pengguna SET"
                            + " username ='" + jUsername.getText() + "',"
                            + " password ='" + jPassword.getText() + "',"
                            + " level ='" + jLevel.getSelectedItem().toString() + "'"
                            + " WHERE idpengguna = " + jID.getText() + "";
                    con.createStatement().executeUpdate(sql);
                    JOptionPane.showMessageDialog(null, "Berhasil Diubah!");
                } catch (Exception e) {
                    JOptionPane.showMessageDialog(null, "Gagal Diubah!");
                }
            } else {
                JOptionPane.showMessageDialog(null, "Password dan Retype password Anda tidak sama!");
            }
        } else {
            validasi();
        }
        awal();
    }//GEN-LAST:event_buttonUbahActionPerformed

    private void buttonTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonTambahActionPerformed
        // TODO add your handling code here:
        if (!jUsername.getText().isEmpty() && !jPassword.getText().isEmpty() && !jRePassword.getText().isEmpty()) {
            // cek yang password dan repassword
            if (jRePassword.getText().equals(jPassword.getText())) {
                try {
                    String sql = "INSERT INTO tabel_pengguna value (null,"
                            + "'" + jUsername.getText() + "',"
                            + "'" + jPassword.getText() + "',"
                            + "'" + jLevel.getSelectedItem().toString() + "'"
                            + ")";
                    con.createStatement().executeUpdate(sql);
                    JOptionPane.showMessageDialog(null, "Berhasil Tambah Data!");
                } catch (Exception e) {
                    JOptionPane.showMessageDialog(null, "Gagal Tambah Data!");
                }
            } else {
                JOptionPane.showMessageDialog(null, "Password dan Retype password Anda tidak sama!");
            }
        } else {
            validasi();
        }
        awal();
    }//GEN-LAST:event_buttonTambahActionPerformed

