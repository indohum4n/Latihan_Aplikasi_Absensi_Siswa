    private void tabelPengguna() {
        String[] judul = {"ID", "Username", "Password", "Level"};
        model = new DefaultTableModel(judul, 0);
        tabelPengguna.setModel(model);
        String sql = "SELECT * FROM tabel_pengguna";

        try {
            rs = con.createStatement().executeQuery(sql);
            while (rs.next()) {
                String id = rs.getString("idpengguna");
                String username = rs.getString("username");
                String password = rs.getString("password");
                String level = rs.getString("level");

                String[] data = {id, username, password, level};
                model.addRow(data);
            }
        } catch (Exception e) {
            System.out.println(e);
        }
    }

