    private void tabelAbsensiMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tabelAbsensiMouseClicked
        // TODO add your handling code here:
        int i = tabelAbsensi.getSelectedRow();

        if (i > -1) {
            jID.setText(model.getValueAt(i, 0).toString());
            jNIS.setText(model.getValueAt(i, 1).toString());
            jNama.setText(model.getValueAt(i, 2).toString());
            jTanggal.setText(model.getValueAt(i, 3).toString());
            jMasuk.setText(model.getValueAt(i, 4).toString());
            jPulang.setText(model.getValueAt(i, 5).toString());
            jKeterangan.setSelectedItem(model.getValueAt(i, 6));
        }

        //disable item on klik
        buttonTambah.setEnabled(false);
        buttonUbah.setEnabled(true);
        buttonHapus.setEnabled(true);
    }//GEN-LAST:event_tabelAbsensiMouseClicked

