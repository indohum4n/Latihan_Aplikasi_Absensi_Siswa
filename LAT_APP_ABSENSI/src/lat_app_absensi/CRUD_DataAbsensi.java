    private void tabelAbsensi() {
        String[] judul = {"ID", "NIS", "Nama", "Tanggal", "Jam Masuk", "Jam Pulang", "Keterangan"};
        model = new DefaultTableModel(judul, 0);
        tabelAbsensi.setModel(model);
        String sql = "SELECT a.*, b.nama FROM tabel_absensi a "
                + "INNER JOIN tabel_siswa b ON a.nis = b.nis";

        try {
            rs = con.createStatement().executeQuery(sql);
            while (rs.next()) {
                String id = rs.getString("idabsensi");
                String nis = rs.getString("nis");
                String nama = rs.getString("nama");
                String tanggal = rs.getString("tanggal");
                String masuk = rs.getString("jam_masuk");
                String pulang = rs.getString("jam_pulang");
                String keterangan = rs.getString("keterangan");

                String[] data = {id, nis, nama, tanggal, masuk, pulang, keterangan};
                model.addRow(data);
            }
        } catch (Exception e) {
            System.out.println(e);
        }
    }

